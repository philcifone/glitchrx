#!/usr/bin/env python3
"""Write web/public/icon.svg: an eclipse sliced into scanlines, some slid
sideways (the shift effect) with a green color fringe. Edit the numbers
here, then run scripts/icons.sh to render the PNGs."""

from pathlib import Path

CREAM, GREEN, BG = "#ebdbb2", "#b8bb26", "#1d2021"
CX = CY = 256
SUN = 150  # radius of the bright disc
MOON = (CX + 10, CY - 7, 124)  # the dark disc over it: x, y, radius
STRIP = 30  # height of one scanline strip
SHIFTS = [0, 0, 0, -30, 44, 0, -60, 20, 0, 0]  # sideways slide per strip
FRINGE = 12  # how far the green copy trails a slid strip


def circle(x: float, y: float, r: float) -> str:
    """A circle as path data (two arcs), for combining into one path."""
    return f"M{x - r} {y}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 {-2 * r} 0z"


def eclipse(fill: str) -> str:
    # The moon is a hole (even-odd fill), not a dark disc painted on top,
    # so no cream can bleed through at the strip edges.
    d = circle(CX, CY, SUN) + circle(*MOON)
    return f'<path d="{d}" fill="{fill}" fill-rule="evenodd"/>'



def main() -> None:
    top = CY - SUN
    out = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">',
        "<!-- glitchrx app icon, generated by scripts/icon.py. -->",
        "<defs>",
    ]
    for i in range(len(SHIFTS)):
        # One pixel of overlap hides seams between neighbouring strips.
        y = top + i * STRIP
        out.append(f'<clipPath id="s{i}"><rect x="0" y="{y}" width="512" height="{STRIP + 1}"/></clipPath>')
    out += ["</defs>", f'<rect width="512" height="512" fill="{BG}"/>', '<g id="art">']
    for i, dx in enumerate(SHIFTS):
        # The clip sits inside the translated group, so it slides along.
        if dx:
            fr = dx - (FRINGE if dx > 0 else -FRINGE)
            out.append(f'<g transform="translate({fr} 0)"><g clip-path="url(#s{i})">{eclipse(GREEN)}</g></g>')
        out.append(f'<g transform="translate({dx} 0)"><g clip-path="url(#s{i})">{eclipse(CREAM)}</g></g>')
    out += ["</g>", "</svg>", ""]
    Path(__file__).resolve().parent.parent.joinpath("web/public/icon.svg").write_text("\n".join(out))


if __name__ == "__main__":
    main()
